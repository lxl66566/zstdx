    assert_eq!(decompress(&mut plain, &dst[..n]), input.len());
    assert_eq!(&plain, &input);
    unsafe { zstd::ZSTD_freeCCtx(cctx) };

    // The decode-side windowLogMax accepts 0 (default) and rejects garbage.
    let dctx = dctx_with(0);
