/// The C harness protocol: offer input in fixed chunks; within a chunk
/// keep calling while input remains; a completed frame with input left
/// re-calls for the next frame; stop at an error.
fn drive_transcript(
    zds: *mut zstd::ZSTD_DStream,
    frame: &[u8],
    in_chunk: usize,
    out_chunk: usize,
    record: &mut Vec<(usize, usize, usize, i32)>,
) {
    let mut out_buf = vec![0u8; out_chunk.max(1)];
    let mut fed = 0usize;
    'outer: while fed < frame.len() {
        let take = if in_chunk > 0 {
            (frame.len() - fed).min(in_chunk)
        } else {
            frame.len() - fed
        };
        let mut zin = zstd::ZSTD_inBuffer {
            src: frame[fed..].as_ptr().cast(),
            size: take,
            pos: 0,
        };
        fed += take;
        loop {
            let mut zout = zstd::ZSTD_outBuffer {
                dst: out_buf.as_mut_ptr().cast(),
                size: out_chunk,
                pos: 0,
            };
            let r = unsafe { zstd::ZSTD_decompressStream(zds, &raw mut zout, &raw mut zin) };
            let err = if is_error(r) {
                error_code(r) as i32
            } else {
                0
            };
            record.push((
                if err == 0 {
                    r
                } else {
                    0
                },
                zin.pos,
                zout.pos,
                err,
            ));
            if err != 0 {
                break 'outer;
            }
            if r == 0 {
                if zin.pos < zin.size {
                    continue;
                }
                break 'outer;
            }
            if zin.pos == zin.size {
                break;
            }
        }
    }
}

