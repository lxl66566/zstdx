    assert_eq!(cp.targetLength, 131_072);
    let cp = zstd::ZSTD_getCParams(100, 0, 0);
    assert_eq!(
        (cp.windowLog, cp.strategy),
        (27, zstd::ZSTD_strategy::ZSTD_btultra2)
    );
