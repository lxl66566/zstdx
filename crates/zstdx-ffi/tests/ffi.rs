    let d = unsafe {
        zstd::ZSTD_decompressDCtx(
            dctx,
            out.as_mut_ptr().cast(),
            out.len(),
            cmp[c1..].as_ptr().cast(),
            c2,
        )
    };
    assert_eq!(d, tail.len());

    // refPrefix mid-frame is stage_wrong.
    unsafe { zstd::ZSTD_CCtx_reset(cctx, 3) };
