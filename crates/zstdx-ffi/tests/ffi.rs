    let wild = zstd::ZSTD_compressionParameters {
        windowLog: 45,
        chainLog: 3,
        hashLog: 77,
        searchLog: 0,
        minMatch: 1,
        targetLength: 999_999,
        strategy: zstd::ZSTD_strategy(12),
    };
    let r = zstd::ZSTD_checkCParams(wild);
    assert_eq!(error_code(r), 42); // parameter_outOfBound
